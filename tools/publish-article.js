// --- Step 9: hash propagation (only if content changed) -------------------------
function sha1(filePath) {
  return execSync(`sha1sum "${filePath}"`).toString().trim().split(/\s+/)[0].replace(/^\\/, '').slice(0, 8);
}
function propagateHashesIfChanged() {
  const cssPath = path.join(root, 'styles.css');
  const jsPath = path.join(root, 'js/site.js');
  const newCssHash = sha1(cssPath);
  const newJsHash = sha1(jsPath);
  const sampleFile = path.join(root, 'index.html');
  const sample = fs.readFileSync(sampleFile, 'utf-8');
  const oldCssHash = (sample.match(/styles\.css\?v=([a-f0-9]+)/) || [])[1];
  const oldJsHash = (sample.match(/site\.js\?v=([a-f0-9]+)/) || [])[1];

  function replaceHashEverywhere(oldHash, newHash, filePattern) {
    if (oldHash === newHash) return 0;
    const out = execSync(`grep -rl "${filePattern}?v=${oldHash}" --include="*.html" "${root}"`, { encoding: 'utf-8' }).trim();
    if (!out) return 0;
    const files = out.split('\n');
    for (const f of files) {
      let t = fs.readFileSync(f, 'utf-8');
      t = t.split(`${filePattern}?v=${oldHash}`).join(`${filePattern}?v=${newHash}`);
      fs.writeFileSync(f, t, 'utf-8');
    }
    return files.length;
  }
  const cssCount = replaceHashEverywhere(oldCssHash, newCssHash, 'styles.css');
  const jsCount = replaceHashEverywhere(oldJsHash, newJsHash, 'site.js');
  console.log(`[9/9] hash propagation: css ${oldCssHash}->${newCssHash} (${cssCount} files), js ${oldJsHash}->${newJsHash} (${jsCount} files)`);
}

// --- Step 10: IndexNow ping (Bing/Yandex/Seznam) ---------------------------------
// Actively pushes new/changed URLs instead of waiting for crawl-budget-limited
// discovery — see the 2026-08-21 Bing Webmaster Tools recommendation. Requires
// the key file <INDEXNOW_KEY>.txt to already exist at the site root (created once,
// not regenerated per publish).
const INDEXNOW_KEY = '59f101195a0bdbe12056d57ae58db180';
async function pingIndexNow() {
  const urlList = [
    'https://coin.ponr.org/',
    'https://coin.ponr.org/articles.html',
    'https://coin.ponr.org/en/',
    'https://coin.ponr.org/en/articles.html',
    `https://coin.ponr.org/${zhPath(CONFIG.slug)}`,
    `https://coin.ponr.org/${enPath(CONFIG.slug)}`,
  ];
  // NOTE: the bulk POST /indexnow endpoint reliably returns 403
  // UserForbiddedToAccessSite for this host even with a byte-correct key file,
  // while the single-URL GET endpoint works (202) — verified by hand on
  // 2026-08-22. Loop GET requests instead until the POST path is understood.
  let okCount = 0;
  for (const url of urlList) {
    try {
      const res = await fetch(`https://api.indexnow.org/indexnow?url=${encodeURIComponent(url)}&key=${INDEXNOW_KEY}`);
      if (res.status === 200 || res.status === 202) okCount++;
    } catch (e) { /* non-fatal, continue */ }
  }
  console.log(`[10/10] IndexNow ping: ${okCount}/${urlList.length} URLs accepted`);
}

