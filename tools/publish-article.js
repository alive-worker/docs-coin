// One-shot site-wide integration for publishing a new article.
// Fill in CONFIG below, then: node tools/publish-article.js
//
// What it does (all 24-30 existing files, both languages):
//   1. Inserts a sidebar <a class="side-item"> entry into every article/404 page.
//   2. Inserts a related-article <li> into every existing article's "related" aside.
//   3. Bumps numberOfItems and prepends a ListItem in the ItemList JSON-LD on
//      index.html / articles.html (zh + en).
//   4. Promotes the new article to the homepage's featured card, demotes the
//      previous featured article to the top of the "latest" grid, and drops the
//      oldest grid card to keep the grid at 9 items (zh + en).
//   5. Inserts an archive-item row into articles.html / en/articles.html.
//   6. Adds <url> entries to sitemap.xml.
//   7. Regenerates feed.xml / en/feed.xml from each article page's own <head> meta.
//   8. Adds DATES entries to js/site.js.
//   9. Recomputes and propagates the styles.css / site.js cache-bust hash IF (and
//      only if) either file's content actually changed (e.g. a new tag color).
//   10. Pings IndexNow (Bing/Yandex/Seznam) with the new/changed URLs so they get
//       actively crawled instead of waiting on a new domain's limited crawl budget.
//   11. Regenerates the 4 topic hub pages (research/<topic>/index.html +
//       en/research/<topic>/index.html) via tools/generate-topic-hubs.js, since
//       the new article changes what each hub's article list contains.
//
// EDITORIAL GUIDELINES (per an external SEO review on 2026-08-22 — read before
// picking a topic or writing a word):
//   1. Stay inside the site's four existing topic buckets (basics/governance/
//      market/protocol) — check the current slug list and topic counts first.
//      Don't drift into adjacent verticals the sibling site ponr.org already
//      owns (payment, subscriptions, virtual cards as a topic in themselves) —
//      that dilutes topic authority for both sites. A virtual-card article is
//      fine ONLY if the angle is genuine crypto-research verification, not
//      "how to pay for X with a card".
//   2. No "what is X" commodity explainer content (what is a stablecoin, what
//      is on-chain analysis, etc.) — LLMs and a hundred other sites already
//      cover that ground, so there's no ranking reason for one more. Every
//      article needs a concrete verification method, numeric threshold, or
//      actionable check that couldn't be generated by a generic prompt.
//   3. Any sponsored/promotional mention must stay a small, clearly-labeled
//      aside inside a research article — never the article's own premise or
//      title (e.g. do NOT write "how to pay for research tools with a virtual
//      card"; DO write a real verification piece that naturally references a
//      tool once, hedged, in one section).
//   4. Prefer claim-level sourcing — link a specific claim to a specific
//      reference near where it's made — over one generic "Sources" list at
//      the article's end.
//
// What it does NOT do (do these yourself first):
//   - Write the article's own two HTML pages (zh + en) at their NEW-scheme paths:
//     research/<topic>/<slug>.html and en/research/<topic>/<slug>.html (topic =
//     CONFIG.topic) — the flat /articles/<slug>.html layout was retired on
//     2026-08-22; every old URL now redirects (client-side canonical + meta
//     refresh stub, since there's no server access for real 301s) to its new
//     research/<topic>/ location. Build the new pages the way past sessions did
//     (clone a similar existing article as a template, splice in the generated
//     sections, keep an eye out for the corruption patterns the verify step
//     catches: truncated paragraphs, "see above" placeholder subsections, a
//     sponsored link that's plain text instead of an <a>).
//   - Add a brand-new archive-tag color to styles.css if the topic needs one not
//     already defined (grep for archive-tag--<color> first).
//   - Draw the AI-tech cover SVGs (zh + en) if the topic is new.
//     Cover accent hue should follow the article's data-topic, not always default
//     teal/blue (that flattened every cover into one look — see the frontend-design
//     pass on 2026-08-21): basics -> blue (#4a7bb0/#6fa8dc family), governance ->
//     indigo/purple, market -> amber/gold (--accent-2 family), protocol -> teal/cyan.
//     Keep dark background + glowing linework, but vary which hue glows so covers
//     read as belonging to different sections, not one repeated template.
//   - Open the article body with an `.article-verify-panel` block (CSS already
//     defined in styles.css) right after the lede paragraph, before the first
//     h2 — a short "核验清单 / Verification checklist" of 3-4 concrete claims the
//     article checks, each as an `<li>` inside `.article-verify-list` with an
//     `.article-verify-check` circle. This is the article-page counterpart to the
//     homepage hero-hud and is what makes a verification-style article visually
//     distinct from a generic blog post — don't skip it for new articles.
//     Existing articles are intentionally left alone (73 files, out of scope).
//
// Idempotent: safe to re-run — each step early-outs if the new slug is already present.

